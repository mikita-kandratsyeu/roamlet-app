export class RequestError extends Error {
  constructor(status) {
    super('Invalid routing request.');
    this.status = status;
  }
}

const PROFILES = new Set(['cycling-regular', 'cycling-road', 'cycling-mountain', 'foot-hiking']);

function record(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function exactKeys(value, allowed) {
  return record(value) && Object.keys(value).every((key) => allowed.includes(key));
}

function coordinate(value, elevation = false) {
  return (
    Array.isArray(value) &&
    (value.length === 2 || (elevation && value.length === 3)) &&
    Array.from(value).every((number) => typeof number === 'number' && Number.isFinite(number)) &&
    Math.abs(value[0]) <= 180 &&
    Math.abs(value[1]) <= 90
  );
}

export function validateBody(body) {
  if (
    !exactKeys(body, [
      'profile',
      'coordinates',
      'instructions',
      'elevation',
      'options',
      'alternative_routes',
    ]) ||
    !PROFILES.has(body.profile) ||
    body.instructions !== false ||
    body.elevation !== true ||
    !Array.isArray(body.coordinates) ||
    body.coordinates.length < 2 ||
    body.coordinates.length > 25 ||
    !Array.from(body.coordinates).every((point) => coordinate(point))
  )
    throw new RequestError(400);

  const upstream = { coordinates: body.coordinates, instructions: false, elevation: true };
  if (Object.hasOwn(body, 'options')) {
    const options = body.options;
    if (
      !exactKeys(options, ['avoid_features']) ||
      !Array.isArray(options.avoid_features) ||
      options.avoid_features.length > 2 ||
      !Array.from(options.avoid_features).every((feature) =>
        ['ferries', 'steps'].includes(feature),
      ) ||
      new Set(options.avoid_features).size !== options.avoid_features.length
    )
      throw new RequestError(400);
    upstream.options = { avoid_features: [...options.avoid_features] };
  }
  if (Object.hasOwn(body, 'alternative_routes')) {
    const alternatives = body.alternative_routes;
    // Only the alternative settings currently generated by the client are accepted.
    if (
      !exactKeys(alternatives, ['target_count', 'weight_factor', 'share_factor']) ||
      alternatives.target_count !== 2 ||
      alternatives.weight_factor !== 1.4 ||
      alternatives.share_factor !== 0.6
    )
      throw new RequestError(400);
    upstream.alternative_routes = { target_count: 2, weight_factor: 1.4, share_factor: 0.6 };
  }
  return { profile: body.profile, upstream };
}

export function sanitizeSuccess(data) {
  if (
    !record(data) ||
    data.type !== 'FeatureCollection' ||
    !Array.isArray(data.features) ||
    data.features.length > 3
  )
    throw new Error('Invalid upstream response.');
  return {
    type: 'FeatureCollection',
    features: data.features.map((feature) => {
      const geometry = feature?.geometry;
      const summary = feature?.properties?.summary;
      if (
        !record(feature) ||
        feature.type !== 'Feature' ||
        !record(geometry) ||
        geometry.type !== 'LineString' ||
        !Array.isArray(geometry.coordinates) ||
        geometry.coordinates.length < 2 ||
        !geometry.coordinates.every((point) => coordinate(point, true)) ||
        !record(summary) ||
        !['distance', 'duration'].every(
          (key) =>
            typeof summary[key] === 'number' && Number.isFinite(summary[key]) && summary[key] >= 0,
        )
      ) {
        throw new Error('Invalid upstream response.');
      }
      return {
        type: 'Feature',
        geometry: {
          type: 'LineString',
          coordinates: geometry.coordinates.map((point) => [...point]),
        },
        properties: { summary: { distance: summary.distance, duration: summary.duration } },
      };
    }),
  };
}
