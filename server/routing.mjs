const REQUEST_LIMIT = 16 * 1024;
const RESPONSE_LIMIT = 8 * 1024 * 1024;
const UPSTREAM_TIMEOUT = 20_000;
const PROFILES = new Set(['cycling-regular', 'cycling-road', 'cycling-mountain', 'foot-hiking']);
const ERROR_CODES = new Set([2004, 2009, 2010]);

class RequestError extends Error {
  constructor(status) {
    super('Invalid routing request.');
    this.status = status;
  }
}

function reply(res, status, body) {
  res.statusCode = status;
  res.setHeader('Cache-Control', 'no-store');
  res.setHeader('Content-Type', 'application/json; charset=utf-8');
  res.setHeader('X-Content-Type-Options', 'nosniff');
  res.end(JSON.stringify(body));
}

function failure(res, status, code) {
  reply(res, status, {
    error: {
      ...(ERROR_CODES.has(code) || (status === 503 && code === 'ROUTING_NOT_CONFIGURED') ? { code } : {}),
      message: status === 400 || status === 413 || status === 415
        ? 'Invalid routing request.'
        : 'The routing service is unavailable.',
    },
  });
}

function header(req, name) {
  const value = req.headers?.[name];
  return typeof value === 'string' ? value : '';
}

function sameOrigin(req) {
  if (header(req, 'sec-fetch-site').toLowerCase() === 'cross-site') return false;
  if (req.headers?.origin === undefined) return true;
  const origin = header(req, 'origin');
  const host = header(req, 'host');
  const protocol = header(req, 'x-forwarded-proto') || (req.socket?.encrypted ? 'https' : 'http');
  if (!host || !['http', 'https'].includes(protocol)) return false;
  try {
    const source = new URL(origin);
    const target = new URL(`${protocol}://${host}`);
    return source.origin === origin && source.origin === target.origin;
  } catch {
    return false;
  }
}

function record(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function exactKeys(value, allowed) {
  return record(value) && Object.keys(value).every((key) => allowed.includes(key));
}

function coordinate(value, elevation = false) {
  return Array.isArray(value) && (value.length === 2 || (elevation && value.length === 3)) &&
    Array.from(value).every((number) => typeof number === 'number' && Number.isFinite(number)) &&
    Math.abs(value[0]) <= 180 && Math.abs(value[1]) <= 90;
}

function validateBody(body) {
  if (!exactKeys(body, ['profile', 'coordinates', 'instructions', 'elevation', 'options', 'alternative_routes']) ||
      !PROFILES.has(body.profile) || body.instructions !== false || body.elevation !== true ||
      !Array.isArray(body.coordinates) || body.coordinates.length < 2 || body.coordinates.length > 25 ||
      !Array.from(body.coordinates).every((point) => coordinate(point))) throw new RequestError(400);

  const upstream = { coordinates: body.coordinates, instructions: false, elevation: true };
  if (Object.hasOwn(body, 'options')) {
    const options = body.options;
    if (!exactKeys(options, ['avoid_features']) || !Array.isArray(options.avoid_features) ||
        options.avoid_features.length > 2 ||
        !Array.from(options.avoid_features).every((feature) => ['ferries', 'steps'].includes(feature)) ||
        new Set(options.avoid_features).size !== options.avoid_features.length) throw new RequestError(400);
    upstream.options = { avoid_features: [...options.avoid_features] };
  }
  if (Object.hasOwn(body, 'alternative_routes')) {
    const alternatives = body.alternative_routes;
    // Only the alternative settings currently generated by the client are accepted.
    if (!exactKeys(alternatives, ['target_count', 'weight_factor', 'share_factor']) ||
        alternatives.target_count !== 2 || alternatives.weight_factor !== 1.4 ||
        alternatives.share_factor !== 0.6) throw new RequestError(400);
    upstream.alternative_routes = { target_count: 2, weight_factor: 1.4, share_factor: 0.6 };
  }
  return { profile: body.profile, upstream };
}

async function readBody(req) {
  const length = header(req, 'content-length');
  if (length && (!/^\d+$/.test(length) || Number(length) > REQUEST_LIMIT)) {
    req.resume?.();
    throw new RequestError(413);
  }
  let raw = req.body;
  if (raw === undefined) {
    raw = await new Promise((resolve, reject) => {
      const chunks = [];
      let size = 0;
      const cleanup = () => {
        req.removeListener('data', data);
        req.removeListener('end', end);
        req.removeListener('error', error);
        req.removeListener('aborted', aborted);
      };
      const error = () => { cleanup(); reject(new RequestError(400)); };
      const aborted = error;
      const data = (chunk) => {
        const buffer = Buffer.isBuffer(chunk) ? chunk : Buffer.from(chunk);
        size += buffer.length;
        if (size > REQUEST_LIMIT) {
          cleanup();
          req.resume();
          reject(new RequestError(413));
        } else chunks.push(buffer);
      };
      const end = () => { cleanup(); resolve(Buffer.concat(chunks)); };
      req.on('data', data);
      req.on('end', end);
      req.on('error', error);
      req.on('aborted', aborted);
      if (req.aborted || req.readableEnded) error();
    });
  }
  try {
    if (Buffer.isBuffer(raw)) raw = raw.toString('utf8');
    const serialized = typeof raw === 'string' ? raw : JSON.stringify(raw);
    if (Buffer.byteLength(serialized, 'utf8') > REQUEST_LIMIT) throw new RequestError(413);
    return typeof raw === 'string' ? JSON.parse(raw) : raw;
  } catch (error) {
    if (error instanceof RequestError) throw error;
    throw new RequestError(400);
  }
}

async function upstreamJson(response, signal) {
  if (Number(response.headers.get('content-length')) > RESPONSE_LIMIT) {
    await response.body?.cancel();
    throw new Error('Invalid upstream response.');
  }
  if (!response.body) throw new Error('Invalid upstream response.');
  const reader = response.body.getReader();
  const cancel = () => { void reader.cancel().catch(() => {}); };
  signal.addEventListener('abort', cancel, { once: true });
  if (signal.aborted) cancel();
  const chunks = [];
  let size = 0;
  try {
    while (true) {
      const { done, value } = await reader.read();
      if (done) break;
      size += value.byteLength;
      if (size > RESPONSE_LIMIT) throw new Error('Invalid upstream response.');
      chunks.push(Buffer.from(value));
    }
    return JSON.parse(Buffer.concat(chunks).toString('utf8'));
  } finally {
    signal.removeEventListener('abort', cancel);
    // Cancel oversized or stalled streams as well as releasing the reader.
    void reader.cancel().catch(() => {});
    reader.releaseLock();
  }
}

function sanitizeSuccess(data) {
  if (!record(data) || data.type !== 'FeatureCollection' || !Array.isArray(data.features) ||
      data.features.length > 3) throw new Error('Invalid upstream response.');
  return {
    type: 'FeatureCollection',
    features: data.features.map((feature) => {
      const geometry = feature?.geometry;
      const summary = feature?.properties?.summary;
      if (!record(feature) || feature.type !== 'Feature' || !record(geometry) ||
          geometry.type !== 'LineString' || !Array.isArray(geometry.coordinates) ||
          geometry.coordinates.length < 2 || !geometry.coordinates.every((point) => coordinate(point, true)) ||
          !record(summary) || !['distance', 'duration'].every((key) =>
            typeof summary[key] === 'number' && Number.isFinite(summary[key]) && summary[key] >= 0)) {
        throw new Error('Invalid upstream response.');
      }
      return {
        type: 'Feature',
        geometry: { type: 'LineString', coordinates: geometry.coordinates.map((point) => [...point]) },
        properties: { summary: { distance: summary.distance, duration: summary.duration } },
      };
    }),
  };
}

function apiKey() {
  return typeof process.env.ORS_API_KEY === 'string' ? process.env.ORS_API_KEY.trim() : '';
}

export async function configHandler(req, res) {
  if (!sameOrigin(req)) return failure(res, 403);
  if (req.method !== 'GET') {
    res.setHeader('Allow', 'GET');
    return failure(res, 405);
  }
  return reply(res, 200, { available: Boolean(apiKey()) });
}

export async function routeHandler(req, res) {
  if (!sameOrigin(req)) return failure(res, 403);
  if (req.method !== 'POST') {
    res.setHeader('Allow', 'POST');
    return failure(res, 405);
  }
  if (!/^application\/json\s*(?:;.*)?$/i.test(header(req, 'content-type'))) return failure(res, 415);
  let request;
  try {
    request = validateBody(await readBody(req));
  } catch (error) {
    return failure(res, error instanceof RequestError ? error.status : 400);
  }
  const key = apiKey();
  if (!key) return failure(res, 503, 'ROUTING_NOT_CONFIGURED');

  const controller = new AbortController();
  let timer;
  let timedOut = false;
  try {
    const result = await Promise.race([
      (async () => {
        const response = await fetch(
          `https://api.heigit.org/openrouteservice/v2/directions/${request.profile}/geojson`,
          {
            method: 'POST',
            headers: { Authorization: key, 'Content-Type': 'application/json', Accept: 'application/geo+json' },
            body: JSON.stringify(request.upstream),
            redirect: 'error',
            credentials: 'omit',
            signal: controller.signal,
          },
        );
        if ([401, 403, 429].includes(response.status)) {
          void response.body?.cancel().catch(() => {});
          return { status: response.status };
        }
        const data = await upstreamJson(response, controller.signal);
        if (!response.ok || (record(data) && Object.hasOwn(data, 'error'))) {
          return {
            status: [400, 404, 422].includes(response.status) ? response.status : 502,
            code: data?.error?.code,
          };
        }
        return { status: 200, body: sanitizeSuccess(data) };
      })(),
      new Promise((_, reject) => {
        timer = setTimeout(() => {
          timedOut = true;
          controller.abort();
          reject(new Error('Routing timeout.'));
        }, UPSTREAM_TIMEOUT);
      }),
    ]);
    if (result.body) return reply(res, 200, result.body);
    return failure(res, result.status, result.code);
  } catch {
    controller.abort();
    return failure(res, timedOut ? 504 : 502);
  } finally {
    clearTimeout(timer);
  }
}
